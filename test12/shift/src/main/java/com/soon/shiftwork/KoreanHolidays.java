package com.soon.shiftwork;

import java.time.*;
import java.util.*;

/** Offline Korean holidays, 2024–2050. Rules as of 2026-10-23; newly declared
 * temporary/election holidays require a data update. See HOLIDAYS.md. */
public final class KoreanHolidays {
    private static final Map<Integer,Map<LocalDate,String>> CACHE=new HashMap<>();
    public static String name(LocalDate date){return year(date.getYear()).getOrDefault(date,"");}
    public static synchronized Map<LocalDate,String> year(int y) {
        if(CACHE.containsKey(y))return CACHE.get(y);
        Map<LocalDate,String> dates=new TreeMap<>();
        if(y<2024||y>2050)return Collections.emptyMap();
        List<List<LocalDate>> groups=new ArrayList<>();
        add(dates,y,1,1,"신정");add(dates,y,6,6,"현충일");
        int[][] solar={{3,1},{5,5},{8,15},{10,3},{10,9},{12,25}};
        String[] names={"삼일절","어린이날","광복절","개천절","한글날","성탄절"};
        for(int i=0;i<solar.length;i++){LocalDate d=add(dates,y,solar[i][0],solar[i][1],names[i]);groups.add(Collections.singletonList(d));}
        if(y>=2026){groups.add(Collections.singletonList(add(dates,y,5,1,"노동절")));groups.add(Collections.singletonList(add(dates,y,7,17,"제헌절")));}
        String[] lunar=LUNAR[y-2024].split(",");
        for(int i=0;i<3;i++) {
            LocalDate center=LocalDate.parse(y+"-"+lunar[i]);
            List<LocalDate> group=new ArrayList<>();
            for(int delta=i==1?0:-1;delta<=(i==1?0:1);delta++) {
                LocalDate d=center.plusDays(delta);group.add(d);
                dates.merge(d,i==0?"설날":i==1?"부처님오신날":"추석",(a,b)->a+" · "+b);
            }
            groups.add(group);
        }
        // Known one-off dates only; never extrapolate future election dates.
        if(y==2024){add(dates,y,4,10,"국회의원 선거일");add(dates,y,10,1,"임시공휴일");}
        if(y==2025){add(dates,y,1,27,"임시공휴일");add(dates,y,6,3,"대통령 선거일");}
        if(y==2026)add(dates,y,6,3,"전국동시지방선거일");
        TreeSet<LocalDate> substitutes=new TreeSet<>();
        for(List<LocalDate> group:groups) {
            boolean needs=false;
            for(LocalDate d:group) {
                int weekday=d.getDayOfWeek().getValue();
                if(weekday==7||(group.size()==1&&weekday==6)||(weekday<6&&dates.get(d).contains(" · ")))needs=true;
            }
            if(needs)substitutes.add(group.get(group.size()-1));
        }
        for(LocalDate end:substitutes) {
            LocalDate next=end.plusDays(1);
            while(next.getDayOfWeek().getValue()>=6||dates.containsKey(next))next=next.plusDays(1);
            dates.put(next,"대체공휴일");
        }
        Map<LocalDate,String> result=Collections.unmodifiableMap(dates);CACHE.put(y,result);return result;
    }
    private static LocalDate add(Map<LocalDate,String> dates,int y,int m,int d,String name){LocalDate date=LocalDate.of(y,m,d);dates.put(date,name);return date;}
    // Solar dates of lunar 1/1, 4/8 and 8/15, generated by scripts/generate-holiday-table.py.
    private static final String[] LUNAR={
        "02-10,05-15,09-17", // 2024
        "01-29,05-05,10-06", // 2025
        "02-17,05-24,09-25", // 2026
        "02-07,05-13,09-15", // 2027
        "01-27,05-02,10-03", // 2028
        "02-13,05-20,09-22", // 2029
        "02-03,05-09,09-12", // 2030
        "01-23,05-28,10-01", // 2031
        "02-11,05-16,09-19", // 2032
        "01-31,05-06,09-08", // 2033
        "02-19,05-25,09-27", // 2034
        "02-08,05-15,09-16", // 2035
        "01-28,05-03,10-04", // 2036
        "02-15,05-22,09-24", // 2037
        "02-04,05-11,09-13", // 2038
        "01-24,04-30,10-02", // 2039
        "02-12,05-18,09-21", // 2040
        "02-01,05-07,09-10", // 2041
        "01-22,05-26,09-28", // 2042
        "02-10,05-16,09-17", // 2043
        "01-30,05-05,10-05", // 2044
        "02-17,05-24,09-25", // 2045
        "02-06,05-13,09-15", // 2046
        "01-26,05-02,10-04", // 2047
        "02-14,05-20,09-22", // 2048
        "02-02,05-09,09-11", // 2049
        "01-23,05-28,09-30", // 2050
    };
}
